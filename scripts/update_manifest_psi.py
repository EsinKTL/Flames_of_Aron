def get_file_info(rel_path):
    p = os.path.join(rel_path)
    if not os.path.exists(p):
        return '', ''
    size = os.path.getsize(p)
    with open(p, 'rb') as f:
        sha = hashlib.sha256(f.read()).hexdigest()
    return str(size), sha

